#!/usr/bin/env python3
"""gen_hle_bindings.py - generate src/port/hle_bindings.cpp from the Ghidra draft stub list.

Every stub of the CoN ELF (recomp/cn_config_ghidra_draft.toml) is bound at start-up to the runtime
handler with the same name (runtime ps2_call_list.h), via ps2_game_overrides::bindAddressHandler.
The generated file is data derived from our own ELF analysis (like recomp/cn_functions.csv) and is
committed; the generator is re-run only when the function map changes.

Usage: python tools/gen_hle_bindings.py [--elf PATH] [--out PATH]
"""
import argparse
import pathlib
import re
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DRAFT = ROOT / "recomp" / "cn_config_ghidra_draft.toml"
OUT = ROOT / "src" / "port" / "hle_bindings.cpp"
ELF = ROOT / "build" / "extracted" / "SLUS_205.65"
ENTRY = 0x00100008


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", default=str(ELF))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()

    draft = DRAFT.read_text(encoding="utf-8", errors="replace")
    start = draft.index("stubs = [")
    end = draft.index("]", start)
    pairs = re.findall(r'"([A-Za-z_]\w*)@(0x[0-9A-Fa-f]+)"', draft[start:end])
    pairs = [(name, int(addr, 16)) for name, addr in pairs]
    pairs.sort(key=lambda p: p[1])

    crc = "0x00000000"
    elf = pathlib.Path(a.elf)
    if elf.exists():
        crc = "0x%08x" % (zlib.crc32(elf.read_bytes()) & 0xFFFFFFFF)
    else:
        print(f"note: {elf} not found; crc32 left 0 (applyMatching falls back to the ELF name)")

    lines = [
        "// Generated by tools/gen_hle_bindings.py - DO NOT EDIT BY HAND.",
        "// Champions of Norrath (USA, SLUS-20565): bind every SDK stub of the ELF to the runtime handler",
        "// with the same name, by address, at start-up (HLE by address; the ELF is stripped).",
        "// Source: recomp/cn_config_ghidra_draft.toml (ExportPS2Functions.java, our own Ghidra analysis).",
        "",
        '#include "game_overrides.h"',
        '#include "ps2_runtime.h"',
        "",
        "#include <cstdio>",
        "",
        "namespace",
        "{",
        "    struct StubBinding",
        "    {",
        "        uint32_t address;",
        '        const char *handler;',
        "    };",
        "",
        f"    constexpr StubBinding kStubBindings[] = {{",
    ]
    for name, addr in pairs:
        lines.append(f'        {{ 0x{addr:08X}u, "{name}" }},')
    lines += [
        "    };",
        "",
        "    void applyConOverrides(PS2Runtime &runtime)",
        "    {",
        "        unsigned bound = 0;",
        "        for (const StubBinding &stub : kStubBindings)",
        "        {",
        "            if (ps2_game_overrides::bindAddressHandler(runtime, stub.address, stub.handler))",
        "                ++bound;",
        "        }",
        '        std::fprintf(stderr, "[hle] Champions of Norrath: %u/%zu SDK stubs bound by address\\n",',
        "                      bound, sizeof(kStubBindings) / sizeof(kStubBindings[0]));",
        "    }",
        "}",
        "",
        "// Matched by ELF name + entry (crc32 when the runtime provides it); see ps2_game_overrides.",
        f'PS2_REGISTER_GAME_OVERRIDE("Champions of Norrath (USA)", "SLUS_205.65", 0x{ENTRY:08X}u, {crc}, applyConOverrides)',
        "",
    ]
    pathlib.Path(a.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {a.out}: {len(pairs)} stub bindings, crc32 {crc}")


if __name__ == "__main__":
    main()
